/** XOR string hiding. Đây là lớp làm rối tĩnh, không phải mã hoá bí mật chống phân tích chuyên sâu. */
internal object StringVault {
    private const val KEY = 0x5A

    fun decode(vararg encoded: Int): String {
        val bytes = ByteArray(encoded.size) { i -> (encoded[i] xor KEY).toByte() }
        return bytes.toString(Charsets.UTF_8)
    }

    fun trafficSignsFile() = decode(0x29, 0x33, 0x3D, 0x34, 0x29, 0x74, 0x30, 0x29, 0x35, 0x34)
    fun hcmSignsFile() = decode(0x29, 0x33, 0x3D, 0x34, 0x29, 0x05, 0x32, 0x39, 0x37, 0x74, 0x30, 0x29, 0x35, 0x34)
    fun camerasFile() = decode(0x39, 0x3B, 0x37, 0x3F, 0x28, 0x3B, 0x29, 0x05, 0x2C, 0x34, 0x74, 0x30, 0x29, 0x35, 0x34)
    fun tftServiceUuid() = decode(
        0x6A,0x6A,0x6A,0x6A,0x6D,0x68,0x68,0x6A,0x77,0x6A,0x6A,0x6A,0x6A,0x77,0x6B,0x6A,0x6A,0x6A,
        0x77,0x62,0x6A,0x6A,0x6A,0x77,0x6A,0x6A,0x62,0x6A,0x6F,0x1C,0x63,0x18,0x69,0x6E,0x1C,0x18
    )
}
